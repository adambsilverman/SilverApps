"""Fill the quiz list in gradebook-sync.html: every Test Yourself page (marked data-sa-quiz="<lesson title>").
Run after the page builds: python3 build/build_quizlist.py"""
import re, json, sys, pathlib, html
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from common import *
out = []
for f in sorted(SITE_DIR.glob("*.html")):
    m = re.search(r'data-sa-quiz="([^"]+)"', f.read_text(encoding="utf-8"))
    if m: out.append({"page": f.stem, "title": html.unescape(m.group(1))})
out.sort(key=lambda q: q["title"].lower())
p = SITE_DIR / "gradebook-sync.html"
s = p.read_text(encoding="utf-8")
s = re.sub(r"/\*QUIZLIST\*/\[.*?\];", lambda m: "/*QUIZLIST*/" + json.dumps(out, ensure_ascii=False) + ";", s, count=1, flags=re.S)
p.write_text(s, encoding="utf-8")
print("quiz list:", len(out), "quizzes")

# ---- the question banks for the test maker (test-maker.html) and the test page (test.html) ----
# Every Test Yourself bank, grouped by quiz, with each quiz's front-page section (build/apps.json). Questions with a notated
# figure are left out (the test page draws no music); hints are dropped, since tests give none.
import hashlib
def js2json(t):
    t = re.sub(r'(?m)^\s*//.*$', '', t); t = re.sub(r',(\s*[\]}])', r'\1', t); return json.loads(t)
cfg = json.loads((ROOT / "build" / "apps.json").read_text(encoding="utf-8"))
SEC = {}
for s in cfg["sections"]:
    for t in s["topics"]:
        for k in ("lesson", "drills"):
            if t.get(k): SEC.setdefault(t[k].replace(".html", ""), s["title"])
units = []
for q in out:
    f = SITE_DIR / (q["page"] + ".html"); s = f.read_text(encoding="utf-8"); bank = None
    for src in re.findall(r'src="(assets/shared/data-[^"?]+\.js)', s):
        mm = re.search(r'window\.FAM\.quiz\s*=\s*(\[.*?\]);\s*(?:\n|$)', (SITE_DIR / src).read_text(encoding="utf-8"), re.S)
        if mm: bank = js2json(mm.group(1))
    if bank is None:
        mm = re.search(r'const QZ = (\[.*?\]);', s, re.S)
        if mm: bank = json.loads(mm.group(1))
    if not bank: continue
    lesson = (re.search(r'lesson:\s*"([^"]+)\.html"', s) or re.search(r'href="([\w-]+-lesson|[\w-]+-what-why-how|[\w-]+-simple-truth)\.html"', s))
    lesson = lesson.group(1) if lesson else q["page"].replace("-quiz", "-lesson")
    qs = [{k: v for k, v in x.items() if k in ("q", "a", "w", "why")} for x in bank if not x.get("fig")]
    units.append({"id": q["page"].replace("-quiz", ""), "title": q["title"], "section": SEC.get(lesson, SEC.get(q["page"].replace("-quiz", ""), "More")), "qs": qs})
order = [s["title"] for s in cfg["sections"]] + ["More"]
units.sort(key=lambda u: (order.index(u["section"]) if u["section"] in order else 99, u["title"].lower()))
bank_js = "/* Generated by build/build_quizlist.py: every Test Yourself question bank, for test-maker.html and test.html. */\nwindow.SA_BANK = " + json.dumps(units, ensure_ascii=False, separators=(",", ":")) + ";\n"
(SITE_DIR / "assets" / "test-bank.js").write_text(bank_js, encoding="utf-8")
ver = hashlib.md5(bank_js.encode("utf-8")).hexdigest()[:8]
for name in ("test-maker.html", "test.html"):
    p = SITE_DIR / name
    if p.exists(): p.write_text(re.sub(r'assets/test-bank\.js(\?v=\w+)?', "assets/test-bank.js?v=" + ver, p.read_text(encoding="utf-8")), encoding="utf-8")
print("test bank:", len(units), "units,", sum(len(u["qs"]) for u in units), "questions")
